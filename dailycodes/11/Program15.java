class TwoDArray{
        public static void main(String[] args){
                float arr2[][] = new float[3][3];

                for(int i=0 ; i<arr2.length ; i++){
                        for(int j=0 ; j<arr2[i].length ; j++){
                                System.out.print(arr2[i][j] + " ");
                        }
                        System.out.println();
                }
        }
}
